#include "pattern.h"

/* 每 tile 8 行, 每行 1 字节, bit0=最左像素, 1=黑
 * 密度严格递增(2048 梯度依赖): 0/6/12.5/25/25/25/50/50/62.5/75/100% */
static const uint8_t s_tiles[PAT_COUNT][8] = {
    /* PAT_EMPTY 0% */
    { 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00 },
    /* PAT_DOT_SPARSE ~6%: 4px 单点 */
    { 0x01, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00 },
    /* PAT_CORNERS 12.5%: 四角 2x2 点 */
    { 0x03, 0x03, 0x00, 0x00, 0x00, 0x00, 0xC0, 0xC0 },
    /* PAT_DOT_DENSE 25%: 2x2 块棋盘格 */
    { 0x33, 0x33, 0xCC, 0xCC, 0x33, 0x33, 0xCC, 0xCC },
    /* PAT_SLASH_S 25%: / 4px 间隔 */
    { 0x11, 0x88, 0x44, 0x22, 0x11, 0x88, 0x44, 0x22 },
    /* PAT_SLASH_S2 25%: \ 4px 间隔 */
    { 0x11, 0x22, 0x44, 0x88, 0x11, 0x22, 0x44, 0x88 },
    /* PAT_SLASH_D 50%: 2px 粗斜纹 */
    { 0x55, 0x55, 0xAA, 0xAA, 0x55, 0x55, 0xAA, 0xAA },
    /* PAT_HLINE 50%: 横线 2px */
    { 0xFF, 0xFF, 0x00, 0x00, 0xFF, 0xFF, 0x00, 0x00 },
    /* PAT_GRID 62.5%: 4px 网格 + 2px 竖条 */
    { 0xFF, 0xC3, 0xC3, 0xC3, 0xFF, 0xC3, 0xC3, 0xC3 },
    /* PAT_CROSS 75%: 交叉双斜线 */
    { 0xFF, 0x99, 0x99, 0xFF, 0xFF, 0x99, 0x99, 0xFF },
    /* PAT_SOLID 100% */
    { 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF },
};

const uint8_t *pat_get(pat_id_t id) {
    if ((int)id < 0 || id >= PAT_COUNT) return s_tiles[PAT_EMPTY];
    return s_tiles[id];
}
